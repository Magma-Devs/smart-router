#!/usr/bin/env bash
# gen-write-methods.sh — regenerate utils/keeper/write_methods_table.go from a lava-specs checkout.
#
# The table is the write-method lock's seed (PRD PER-CHAIN-ERROR-CLASSIFICATION §5.3, MAG-5593):
# every api lava-specs marks `category.stateful: 1`, keyed the way the router identifies an api at
# load time (utils/keeper/write_methods.go, writeMethodKey). An entry the catalog also declares as a
# read somewhere (stateful 0 on another chain: eth_submitWork is a write on ETC and a read on
# fourteen other EVM chains) is qualified with the specs that declare it a write, so it forces
# nothing on the chains that read it. XRP's submit and submit_multisigned are qualified by hand, as
# the PRD asks for generic names.
#
# Usage: scripts/gen-write-methods.sh <lava-specs checkout> [<output .go file>]
# Needs jq and gofmt. Prints the lava-specs commit it read, which the header of the file records.
set -euo pipefail
export LC_ALL=C

usage() { echo "usage: $0 <lava-specs-dir> [output.go]" >&2; exit 2; }
[[ $# -ge 1 && $# -le 2 ]] || usage
SPECS_DIR=$1
OUT=${2:-"$(cd "$(dirname "$0")/.." && pwd)/utils/keeper/write_methods_table.go"}
[[ -d "$SPECS_DIR" ]] || { echo "not a directory: $SPECS_DIR" >&2; exit 1; }
command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }
command -v gofmt >/dev/null || { echo "gofmt is required" >&2; exit 1; }

COMMIT=$(git -C "$SPECS_DIR" rev-parse --short=8 HEAD 2>/dev/null || echo unknown)

# Names the PRD qualifies although no spec declares them as a read: "<interface> <name>".
HAND_QUALIFIED=("jsonrpc submit" "jsonrpc submit_multisigned")

# Fields are joined with the unit separator: a tab is IFS whitespace, so `read` would fold the empty
# verb and internal path of a JSON-RPC row into its neighbours.
US=$'\x1f'

# Every api of every spec at the top of the checkout (the files the router fetches), one row each:
# interface, REST verb, internal path, name, stateful, spec index.
rows() {
  jq -r --arg us "$US" '
    .proposal.specs[]? as $s
    | $s.api_collections[]? as $c
    | ($c.collection_data // {}) as $d
    | $c.apis[]?
    | select(.name != null)
    | [ ($d.api_interface // "?"), ($d.type // ""), ($d.internal_path // ""), .name,
        ((.category.stateful // 0) | tostring), $s.index ] | join($us)' "$SPECS_DIR"/*.json 2>/dev/null | sort -u
}

ROWS=$(rows)
[[ -n "$ROWS" ]] || { echo "no api found under $SPECS_DIR" >&2; exit 1; }

# The lock's key for a row, the same as writeMethodKey in Go: a REST api is its verb and full route
# (internal path and name), every other interface its name.
key() { # iface verb ipath name
  if [[ "$1" == "rest" ]]; then printf '%s%s%s%s%s' "$1" "$US" "$2" "$US" "$3$4"; else printf '%s%s%s%s' "$1" "$US" "$US" "$4"; fi
}

declare -A WRITERS READERS VERB IPATH NAME
while IFS=$US read -r iface verb ipath name st spec; do
  k=$(key "$iface" "$verb" "$ipath" "$name")
  if [[ "$st" == "1" ]]; then
    WRITERS["$k"]="${WRITERS["$k"]:-} $spec"
    VERB["$k"]=$verb; IPATH["$k"]=$ipath; NAME["$k"]=$name
  else
    READERS["$k"]=1
  fi
done <<<"$ROWS"

in_hand_list() {
  local probe=$1 e
  for e in "${HAND_QUALIFIED[@]}"; do [[ "$e" == "$probe" ]] && return 0; done
  return 1
}

go_quote() { printf '%s' "$1" | jq -R -s '.'; }

{
  cat <<EOF
// Code generated by scripts/gen-write-methods.sh from lava-specs ${COMMIT}; DO NOT EDIT.
// Regenerate: scripts/gen-write-methods.sh <lava-specs checkout>

package keeper

// writeMethodsTable is every api lava-specs marked stateful at ${COMMIT}, the seed of the write-method
// lock (PRD §5.3, MAG-5593). An entry with Specs applies only to those specs and the specs that import
// them: the catalog declares the same api a read elsewhere, or the PRD names it a generic name.
var writeMethodsTable = []writeMethod{
EOF
  for k in "${!WRITERS[@]}"; do printf '%s\n' "$k"; done | sort | while IFS= read -r k; do
    IFS=$US read -r iface _ _ <<<"$k"
    verb=${VERB["$k"]}; ipath=${IPATH["$k"]}; name=${NAME["$k"]}
    fields="Interface: $(go_quote "$iface")"
    [[ -n "$verb" && "$iface" == "rest" ]] && fields+=", Verb: $(go_quote "$verb")"
    [[ -n "$ipath" && "$iface" == "rest" ]] && fields+=", InternalPath: $(go_quote "$ipath")"
    fields+=", Name: $(go_quote "$name")"
    if [[ -n "${READERS["$k"]:-}" ]] || in_hand_list "$iface $name"; then
      specs=$(tr ' ' '\n' <<<"${WRITERS["$k"]}" | sed '/^$/d' | sort -u | while read -r s; do go_quote "$s"; done | paste -sd, - | sed 's/,/, /g')
      fields+=", Specs: []string{${specs}}"
    fi
    printf '\t{%s},\n' "$fields"
  done
  echo "}"
} > "$OUT.tmp"
gofmt "$OUT.tmp" > "$OUT" && rm -f "$OUT.tmp"
echo "wrote $OUT from lava-specs $COMMIT: $(grep -c '^	{' "$OUT") entries"
