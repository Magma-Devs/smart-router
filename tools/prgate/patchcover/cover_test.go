// loopsSource holds every other kind of statement: loops, a type switch, a
// select, a function literal and a label. realCoverage runs it with
// Loops([]int{1}, make(chan int), 1), so the string case, the receive case
// and the literal's body never run.
const loopsSource = `package pkg

func Loops(xs []int, ch chan int, v any) int {
	total := 0
	for i := 0; i < len(xs); i++ {
		total += xs[i]
	}
	for _, x := range xs {
		total -= x
	}
	switch v.(type) {
	case int:
		total++
	case string:
		total--
	}
	select {
	case n := <-ch:
		total += n
	default:
		total *= 2
	}
	run := func() { total = 0 }
	_ = run
outer:
	for {
		break outer
	}
	return total
}
`

// realCoverage runs the go tool on the repository and returns the profile it
// writes. Measure is checked against it, so a change in how cover lays out its
// blocks shows up here rather than as a wrong verdict on a pull request.
func realCoverage(t *testing.T, root string) *Coverage {
	t.Helper()
	goTool, err := exec.LookPath("go")
	if err != nil {
		t.Skip("the go tool is not on PATH")
	}
	write(t, root, "pkg/a_test.go", "package pkg\n\nimport \"testing\"\n\nfunc TestAll(t *testing.T) {\n\tSum(1, 2)\n\tPick(1)\n\tLoops([]int{1}, make(chan int), 1)\n}\n")
	write(t, root, "pkg/loops.go", loopsSource)
	profile := filepath.Join(t.TempDir(), "cover.out")
	cmd := exec.Command(goTool, "test", "./...", "-count=1", "-covermode=set", "-coverpkg=./...", "-coverprofile="+profile)
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOWORK=off")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go test: %v\n%s", err, out)
	}
	f, err := os.Open(profile)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	cov := NewCoverage()
	if err := cov.AddProfile(f, mod, "."); err != nil {
		t.Fatal(err)
	}
	return cov
}

func TestMeasureAgainstRealProfile(t *testing.T) {
	root := repo(t)
	cov := realCoverage(t, root)
	every := func(from, to int) *FileDiff {
		fd := &FileDiff{}
		for n := from; n <= to; n++ {
			fd.Added = append(fd.Added, AddedLine{Number: n, Text: "x"})
		}
		return fd
	}
	res, err := Measure(map[string]*FileDiff{"pkg/a.go": every(4, 21), "pkg/loops.go": every(4, 30)}, cov, root, []string{"."})
	if err != nil {
		t.Fatal(err)
	}
	want := []FileResult{
		{Path: "pkg/a.go", Coverable: 11, Covered: 6, Uncovered: []Range{{5, 5}, {13, 13}, {19, 20}}},
		// 21 statements: a for header is one statement, its init and post are
		// part of it; the receive of a select case is part of the case; the
		// label is not one; line 23 holds two, the literal's body never ran.
		{Path: "pkg/loops.go", Coverable: 21, Covered: 16, Uncovered: []Range{{14, 15}, {18, 19}, {23, 23}}},
	}
	if !reflect.DeepEqual(res.Files, want) {
		t.Fatalf("against a real profile:\n got %+v\nwant %+v", res.Files, want)
	}
}
